import {test,expect} from '@playwright/test';
test('equipment booking, return, stocktake and staff permissions',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Your equipment, accounted for.'})).toBeVisible();
 await expect(page.getByText('Demo workspace',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Add equipment',exact:true}).click();
 await page.getByLabel('Equipment name').fill('Test projector');
 await page.getByLabel('Unique asset tag').fill('TEST-QR-01');
 await page.getByLabel('Storage location').fill('Meeting room 1');
 await page.getByRole('button',{name:'Add to equipment register'}).click();
 await page.getByRole('textbox',{name:'Search equipment'}).fill('Test projector');
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await page.getByRole('button',{name:'Book out',exact:true}).click();
 await page.getByRole('button',{name:'Confirm book-out'}).click();
 await expect(page.locator('tbody tr').getByText('Marcus Vance')).toBeVisible();
 await page.getByRole('button',{name:'Book in',exact:true}).click();
 await page.getByLabel('Condition on return').selectOption('Faulty');
 await page.getByRole('button',{name:'Confirm book-in'}).click();
 await expect(page.locator('tbody tr').getByText('Maintenance',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Annual stocktake',exact:true}).click();
 await page.getByRole('button',{name:'Start stocktake',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Start stocktake',exact:true}).click();
 await page.getByRole('button',{name:'Scan equipment',exact:true}).last().click();
 await page.getByLabel('Asset tag or label URL').fill('TEST-QR-01');
 await page.getByRole('button',{name:'Find equipment'}).click();
 await expect(page.getByRole('dialog').getByRole('img',{name:'QR label for TEST-QR-01'})).toBeVisible();
 await page.getByRole('button',{name:'Confirm equipment is present'}).click();
 await expect(page.getByText('Equipment accounted for in the current stocktake',{exact:true})).toBeVisible();
 await page.getByRole('combobox',{name:'Demo role'}).selectOption('demo-staff');
 await expect(page.getByRole('button',{name:'Add equipment',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Audit log',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Scan equipment',exact:true}).click();
 await page.getByLabel('Asset tag or label URL').fill('AST-IT-0002');
 await page.getByRole('button',{name:'Find equipment'}).click();
 await expect(page.getByRole('button',{name:'Confirm equipment is present'})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Book in equipment'})).toHaveCount(0);
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.reload();
 await page.getByRole('textbox',{name:'Search equipment'}).fill('Test projector');
 await expect(page.locator('tbody tr')).toHaveCount(1);
});
