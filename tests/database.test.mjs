import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('database permissions and equipment lifecycle',async()=>{
 const db=new PGlite();
 await db.exec(`create role authenticated; create schema auth; create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}'); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$; grant usage on schema public,auth to authenticated; grant execute on function auth.uid() to authenticated;`);
 await db.exec(await readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
 await db.exec(`grant select,insert,update,delete on all tables in schema public to authenticated; insert into auth.users(id,email) values ('00000000-0000-0000-0000-000000000001','admin@example.com'),('00000000-0000-0000-0000-000000000002','staff@example.com'),('00000000-0000-0000-0000-000000000003','other@example.com'); update profiles set approved=true; update profiles set role='admin' where id='00000000-0000-0000-0000-000000000001';`);
 const actor=async n=>{await db.exec(`reset role; select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-00000000000${n}',false);set role authenticated;`)};
 await db.exec("update profiles set approved=false where id='00000000-0000-0000-0000-000000000003'");
 await actor(3);
 assert.equal((await db.query('select * from assets')).rows.length,0);
 await assert.rejects(db.query("select checkout_asset(gen_random_uuid(),now()+interval '7 days')"),/Approved staff/);
 await actor(1);
 await db.query("select set_staff_access('00000000-0000-0000-0000-000000000003',true,'Finance')");
 await actor(2);
 await assert.rejects(db.query(`select manage_asset($1::jsonb)`,[JSON.stringify({tag:'IT-1'})]),/Administrator/);
 await db.exec(`update profiles set approved=true; update profiles set role='admin' where id=auth.uid()`);
 assert.equal((await db.query('select role from profiles')).rows[0].role,'staff','RLS prevents self promotion');
 await actor(1);
 const payload={tag:'IT-1',name:'Projector',category:'Audiovisual & Cameras',serial:'P001',department:'IT & Systems',location:'Store',condition:'Good',value:100};
 await db.query('select manage_asset($1::jsonb)',[JSON.stringify(payload)]);
 const id=(await db.query('select id from assets')).rows[0].id;
 await db.query(`select start_stocktake('Annual check')`);
 await actor(2);
 await db.query(`select checkout_asset($1,now()+interval '7 days')`,[id]);
 await assert.rejects(db.query(`select checkout_asset($1,now()+interval '7 days')`,[id]),/not available/);
 await actor(3);
 await assert.rejects(db.query(`select return_asset($1,'Good')`,[id]),/Only the borrower/);
 await assert.rejects(db.query(`select verify_asset($1,'QR')`,[id]),/current custodian/);
 assert.equal((await db.query('select * from loans')).rows.length,0,'Other staff cannot read private loans');
 await actor(2);
 await db.query(`select verify_asset($1,'QR')`,[id]);
 await db.query(`select verify_asset($1,'NFC')`,[id]);
 assert.equal((await db.query('select * from checks')).rows.length,1,'Repeated scans are idempotent');
 await db.query(`select return_asset($1,'Faulty')`,[id]);
 assert.equal((await db.query('select status from assets')).rows[0].status,'Maintenance');
 assert.ok((await db.query('select returned_at from loans')).rows[0].returned_at);
 await assert.rejects(db.query(`select checkout_asset($1,now()+interval '7 days')`,[id]),/not available/);
 await assert.rejects(db.exec(`insert into audit(action,actor_name) values('fake','fake')`),/row-level security/);
 await actor(1);
 await db.query('select manage_asset($1::jsonb,$2)',[JSON.stringify({status:'Retired'}),id]);
 assert.ok((await db.query('select retired_at from assets')).rows[0].retired_at);
 assert.ok((await db.query('select * from audit')).rows.length>=6);
 await db.close();
});
